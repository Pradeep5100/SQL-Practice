#CREATING TABLE
CREATE TABLE PRODUCTS(
PRODUCT_ID INT PRIMARY KEY AUTO_INCREMENT,
PRODUCT_NAME VARCHAR(30),
CATEGORY VARCHAR(25),
PRICE INT,
PRODUCT_STATUS VARCHAR(30)
);
SHOW TABLES;

#TO DESCRIBE THE STRUCTURE OF THE TABLE
DESC PRODUCTS;

#SHOWS THE ENTIRE DATA OF THE TABLE
SELECT * FROM PRODUCTS;

#SHOWS DATAS IN PERTICULAR COLUMN
SELECT CATEGORY FROM PRODUCTS;
SELECT CATEGORY,PRICE FROM PRODUCTS;

