#AGGRIGATION FUNCTION
#COUNT FUNCTION.   :  USED TO COUNT ALL THE RECORDS IN THE TABLE
SELECT COUNT(*) FROM SALES;

SELECT COUNT(*) AS TOTAL_PRODUCT FROM SALES;

#SUM FUNCTION

SELECT SUM(QUANTITY) AS TOTAL_QUANTITY FROM SALES;

SELECT SUM(QUANTITY) FROM SALES;

#AVERAGE FUNCTION
SELECT AVG(PRICE) AS TOTAL_AVERAGE FROM SALES;

#MINIMUM FUNCTION
SELECT MIN(PRICE) AS MINIMUM_PRICE FROM SALES;

#MAXIMUM FUNCTION
SELECT MAX(PRICE) AS MAX_PRICE FROM SALES;

SELECT MIN(PRICE), MAX(PRICE) FROM SALES;

#GROUP BY FUNCTION: AGGREGATING DATA BY CATEGORY
#USED TO GROUP ROWS HAVING THE SAME VALUE IN A COLUMN AND APPLY AGGREGATION FUNCTION

SELECT CATEGORY, COUNT(*) AS TOTAL_PRODUCTS FROM SALES
GROUP BY CATEGORY;

 SELECT CATEGORY, SUM(QUANTITY) AS TOTAL_QUANTITY FROM SALES
 GROUP BY CATEGORY;
 
 SELECT CATEGORY, AVG(PRICE) AS AVG_PRICE FROM SALES
 GROUP BY CATEGORY;
 
 #HAVING CLAUSE  : HAVING FILTERS GROUPS AFTER AGGREGATION
 #WHILE (WHERE) FILTERS USED BEFORE AGGREGATION
 
 SELECT CATEGORY, SUM(PRICE) AS TOTAL_PRICE FROM SALES
 GROUP BY CATEGORY HAVING TOTAL_PRICE > 10000;
 
 #ORDER BY
 SELECT CATEGORY,SUM(PRICE) AS TOTAL_PRICE FROM SALES
 GROUP BY CATEGORY ORDER BY TOTAL_PRICE DESC;
 
