#JOINS
CREATE DATABASE JOINS_DB;
USE JOINS_DB;

CREATE TABLE STUDENTS(
STUDENT_ID INT PRIMARY KEY,
STUDENT_NAME VARCHAR(30)
);

INSERT INTO STUDENTS(STUDENT_ID,STUDENT_NAME)VALUES
(1,'A'),
(2,'B'),
(3,'C'),
(4,'D');

CREATE TABLE MARKS(
STUDENT_ID INT,
MARKS INT,
FOREIGN KEY(STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID)
);

INSERT INTO MARKS(STUDENT_ID,MARKS)VALUES
(1,90),
(2,85),
(4,75);

SELECT * FROM STUDENTS;
SELECT * FROM MARKS;

#INNER JOIN

SELECT STUDENTS.STUDENT_ID,STUDENTS.STUDENT_NAME,MARKS.MARKS FROM STUDENTS
INNER JOIN MARKS ON STUDENTS.STUDENT_ID=MARKS.STUDENT_ID;

#LEFT JOIN
SELECT STUDENTS.STUDENT_ID,STUDENTS.STUDENT_NAME,MARKS.MARKS FROM STUDENTS
LEFT JOIN MARKS ON STUDENTS.STUDENT_ID=MARKS.STUDENT_ID;

#RIGHT JOIN
SELECT STUDENTS.STUDENT_ID,STUDENTS.STUDENT_NAME,MARKS.MARKS FROM STUDENTS
RIGHT JOIN MARKS ON STUDENTS.STUDENT_ID=MARKS.STUDENT_ID;


#FULL JOIN
SELECT STUDENTS.STUDENT_ID,STUDENTS.STUDENT_NAME,MARKS.MARKS FROM STUDENTS
LEFT JOIN MARKS ON STUDENTS.STUDENT_ID=MARKS.STUDENT_ID
UNION
SELECT STUDENTS.STUDENT_ID,STUDENTS.STUDENT_NAME,MARKS.MARKS FROM STUDENTS
RIGHT JOIN MARKS ON STUDENTS.STUDENT_ID=MARKS.STUDENT_ID;


SELECT STUDENTS.STUDENT_ID,STUDENTS.STUDENT_NAME,MARKS.MARKS FROM STUDENTS
LEFT JOIN MARKS ON STUDENTS.STUDENT_ID=MARKS.STUDENT_ID
UNION ALL
SELECT STUDENTS.STUDENT_ID,STUDENTS.STUDENT_NAME,MARKS.MARKS FROM STUDENTS
RIGHT JOIN MARKS ON STUDENTS.STUDENT_ID=MARKS.STUDENT_ID;

#SELF JOIN. : A TABLE JOINS ITSELF
CREATE TABLE EMPLOYEES(
EMP_ID INT PRIMARY KEY,
EMP_NAME VARCHAR(50),
MANAGER_ID INT
);

INSERT INTO EMPLOYEES VALUES
(1,'A',NULL),                  -- A IS A BOSS NO MANAGER 
(2,'B',1),
(3,'C',1),
(4,'D',2);

SELECT * FROM EMPLOYEES;

SELECT E1.EMP_NAME AS EMPLOYEE, E2.EMP_NAME AS MANAGER FROM EMPLOYEES E1
LEFT JOIN EMPLOYEES E2 ON E1.MANAGER_ID=E2.EMP_ID;

#CROSS JOIN  :  A CROSS JOIN RETURNS ALL POSSIBLE COMBINITIONS.   IT ALSO CALLED AS CARTISION PRODUCT

SELECT STUDENTS.STUDENT_NAME,MARKS.MARKS FROM STUDENTS CROSS JOIN MARKS;

