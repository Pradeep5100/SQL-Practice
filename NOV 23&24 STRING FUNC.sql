#REPLACE  : USED TO REPLACE A SUBSTING INSIDE A STRING
SELECT CUST_NAME, REPLACE(EMAIL,'gmail','yahoo') AS NEW_EMAIL FROM CUSTOMERS;

#CONCAT FUNCTION

SELECT CONCAT(CUST_NAME,'-',CITY) AS CUSTOMER_DETAILS FROM CUSTOMERS;

#UPPER() OR LOWER() FUNCTION
SELECT UPPER(CUST_NAME) AS NAME_IN_IPPERCASE FROM CUSTOMERS;

SELECT LOWER(CUST_NAME) AS NAME_IN_LOWER FROM CUSTOMERS;

USE STRINGFNS;
SHOW TABLES;

SELECT * FROM CUSTOMERS;

#TRIN FUNCTION. :  REMOVES WHITE SPACES FROM BEGINING AND END
SELECT TRIM('     I AM PRADEEP      ') AS TRIMMED_TEXT;

#PADDING LPAD/RPAD. :   PAD CHARACTERS TO THE LEFT OR RIGHT
#LPAD
SELECT LPAD(CUST_NAME,10,'*') AS LEFT_PAD FROM CUSTOMERS;

#RPAD
SELECT RPAD(CUST_NAME,10,'#') AS RIGHT_PAD FROM CUSTOMERS;

#SUBSTRING. :   EXTRACT A POSITION OF THE STRING
SELECT CUST_NAME, EMAIL, SUBSTRING(EMAIL,2,5) AS EMAIL_START FROM CUSTOMERS;