#STRING FUNCTION
CREATE DATABASE STRINGFNS;
USE STRINGFNS;

CREATE TABLE CUSTOMERS(
CUST_ID INT PRIMARY KEY AUTO_INCREMENT,
CUST_NAME VARCHAR(30),
EMAIL VARCHAR(50),
CITY VARCHAR(30)
);

DESC CUSTOMERS;

