USE SLADB;
SHOW TABLES;
SELECT * FROM STUDENTS;

SELECT STUD_NAME,JOIN_DATE, YEAR(JOIN_DATE) AS YEAR_JOINED FROM STUDENTS;

SELECT STUD_NAME, MONTH(JOIN_DATE) AS MONTH_JOINED FROM STUDENTS;

SELECT STUD_NAME, DAY(JOIN_DATE) AS DAY_JOINED FROM STUDENTS;

#DIFFERENCE IN DAYS
SELECT DATEDIFF('2025-12-31','2024-12-31') AS DAYS_LEFT;

#DIFFERENCE IN TIME
SELECT TIMEDIFF('12:12:34','16:23:45') AS TIME_LEFT;

#TIMESTAMDIFFM : USED TO RETURN THE DIFFERENCE IN A SPECIFIC UNIT

SELECT STUD_NAME,
TIMESTAMPDIFF(YEAR,JOIN_DATE,NOW()) AS YEARS_COMPLETED FROM STUDENTS;

SELECT STUD_NAME, TIMESTAMPDIFF(MONTH,JOIN_DATE,NOW()) AS MONTHS_COMPLETED FROM STUDENTS;

SELECT STUD_NAME, TIMESTAMPDIFF(DAY, JOIN_DATE,NOW()) AS DAYS_COMPLETED FROM STUDENTS;

#DATE FORMAT()  : DATE FORMATING

SELECT DATE_FORMAT('2025-02-15','%d-%m-%Y');

#FORMAT AS DD-MM-YYYY
SELECT DATE_FORMAT("2025-02-15",'%d-%m-%Y');

#DISPLAY THE FULL MONTH NAME
SELECT DATE_FORMAT('2025-02-15','%M');

#DISPLAY THE 2 DIGIT YEAR
SELECT DATE_FORMAT('2025-02-15','%y');

#DISPLAY THE SHORT MONTH NAME
SELECT DATE_FORMAT('2025-02-15','%b');

#DISPLAY THE FULL WEEK NAME
SELECT DATE_FORMAT('2025-02-15','%W');

#DISPLAY SHORT WEEK NAME
SELECT DATE_FORMAT('2025-02-15','%a');

#DISPLAY DATE AND TIME
SELECT DATE_FORMAT('2025-02-15 14:30:45','%d-%m-%Y  %h:%i:%s %p');